let currentClubId = 'MAS';

function toggleLangDropdown(e) {
    if (e) e.stopPropagation();
    const list = document.getElementById('lang-list');
    if (list) list.classList.toggle('show');
}

function handleLangChange(lang) {
    setLanguage(lang);
    const list = document.getElementById('lang-list');
    if (list) list.classList.remove('show');
}

function setLanguage(lang) {
    localStorage.setItem('selectedLang', lang);
    const elements = document.querySelectorAll('[data-i18n]');
    const t = translations[lang];

    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t && t[key]) {
            el.innerHTML = t[key];
        }
    });

    // Update current club description based on language
    if (typeof showClub === 'function') {
        showClub(currentClubId);
    }

    const logoImg = document.getElementById('main-logo');
    if (logoImg) {
        logoImg.src = (lang === 'ko') ? 'logo_b.svg' : 'logo_c.svg';
    }

    const langNames = { ko: 'KR', en: 'EN', ch: 'CH' };
    const currentLangText = document.getElementById('current-lang');
    if (currentLangText) currentLangText.innerText = langNames[lang];
}

function shareSite() {
    const url = window.location.href;
    navigator.clipboard.writeText(url).then(() => {
        alert('주소가 복사되었습니다. 원하는 곳에 붙여넣어 공유하세요!');
    }).catch(err => {
        console.error('Copy failed', err);
    });
}

window.onclick = function(event) {
    if (!event.target.matches('.lang-box') && !event.target.matches('.lang-box *')) {
        const list = document.getElementById('lang-list');
        if (list) list.classList.remove('show');
    }
}

function scrollToTop() {
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

window.onscroll = function() {
    const btn = document.getElementById("back-to-top");
    if (btn) {
        if (document.body.scrollTop > 300 || document.documentElement.scrollTop > 300) {
            btn.classList.add("show");
        } else {
            btn.classList.remove("show");
        }
    }
};

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('selectedLang') || 'ko';
    setLanguage(savedLang);
});
